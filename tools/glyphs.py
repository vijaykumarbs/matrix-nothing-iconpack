G: dict[str, Glyph] = {}


def add(name: str, glyph: Glyph) -> None:
    G[name] = set(glyph)


# --------------------------------------------------------------------------
# shared building blocks
# --------------------------------------------------------------------------
def bubble(x0=1, y0=2, x1=11, y1=8) -> Glyph:
    g = outline(x0, y0, x1, y1)
    for cx, cy, sx, sy in ((x0, y0, 1, 1), (x1, y0, -1, 1), (x0, y1, 1, -1), (x1, y1, -1, -1)):
        g -= dots((cx, cy), (cx + sx, cy), (cx, cy + sy))
    return g


def bubble_tail(x=3, y=8) -> Glyph:
    return dots((x, y + 1), (x - 1, y + 2), (x, y + 2), (x + 1, y + 2))


def rounded(x0, y0, x1, y1, r=1) -> Glyph:
    g = outline(x0, y0, x1, y1)
    for cx, cy, sx, sy in ((x0, y0, 1, 1), (x1, y0, -1, 1), (x0, y1, 1, -1), (x1, y1, -1, -1)):
        g -= dots((cx, cy), (cx + sx, cy), (cx, cy + sy))
    if r > 0:
        for cx, cy, sx, sy in ((x0, y0, 1, 1), (x1, y0, -1, 1), (x0, y1, 1, -1), (x1, y1, -1, -1)):
            g -= dots((cx + sx, cy + sy))
    return g


def play_tri(cx=6.5, cy=6.0, s=2.6) -> Glyph:
    return tri((cx - s * 0.7, cy - s), (cx - s * 0.7, cy + s), (cx + s, cy))


def arrow_up(cx=6, y0=2, y1=10, head=2) -> Glyph:
    return (
        line(cx, y0, cx, y1)
        | line(cx, y0, cx - head, y0 + head)
        | line(cx, y0, cx + head, y0 + head)
    )


