"""Glyph library: every shape is a set of dots on a 13 x 13 matrix.

Design rules
------------
* Art lives inside the 11 x 11 centre so it survives circular launcher masks.
* Strokes are one dot wide (matrix look), solids are filled.
* No two app icons share a glyph unless they are obviously the same product.
"""

