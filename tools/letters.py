def letter(char: str, x: int | None = None, y: int | None = None) -> Glyph:
    """Single letter centred on the matrix (or placed at x, y)."""
    rows = _FONT[char.upper()]
    w = max(len(r) for r in rows)
    if x is None:
        x = (GRID - w) // 2
    if y is None:
        y = (GRID - H) // 2
    out: Glyph = set()
    for row, line_str in enumerate(rows):
        for col, ch in enumerate(line_str):
            if ch == "#":
                px, py = x + col, y + row
                if 0 <= px < GRID and 0 <= py < GRID:
                    out.add((px, py))
    return out


def word(text: str, gap: int = 1) -> Glyph:
    """Lay out a short word, centred horizontally."""
    glyphs = []
    for ch in text:
        rows = _FONT[ch.upper()]
        w = max(len(r) for r in rows)
        g: Glyph = set()
        for row, line_str in enumerate(rows):
            for col, c in enumerate(line_str):
                if c == "#":
                    g.add((col, row))
        glyphs.append((g, w))
    total = sum(w for _, w in glyphs) + gap * (len(glyphs) - 1)
    x = (GRID - total) // 2
    out: Glyph = set()
    for g, w in glyphs:
        for (px, py) in g:
            out.add((px + x, py + (GRID - H) // 2))
        x += w + gap
    return out
